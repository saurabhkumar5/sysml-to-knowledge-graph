"""
Dynamic mapping: keep the knowledge graph in sync with the SysML model.

Idea (lesson 4): SysON keeps only "the one and only commit", so we keep our own
snapshots. Every sync:
  1. read the current model (SysML v2 API, or a JSON file)
  2. map it to a graph            (same rules as sysml_to_graph.py)
  3. compare with the last graph  (by SysML @id)
  4. write ONLY the changes as Cypher -> data/changes.cypher
  5. optionally apply them to Neo4j (--apply)

Usage (from the project root):
    python3 mapper/sync.py                      # one sync from the API
    python3 mapper/sync.py --apply              # ... and update Neo4j
    python3 mapper/sync.py --apply --watch 30   # check every 30 s (dynamic)
    python3 mapper/sync.py --elements file.json # use a JSON file instead of the API
"""
import argparse
import datetime
import json
import os
import subprocess
import sys
import time
import tomllib

sys.path.insert(0, os.path.dirname(__file__))
from fetch_model import API, DEFAULT_PROJECT, get_json   # noqa: E402
from sysml_to_graph import RULES_FILE, Mapper, props      # noqa: E402

GRAPH_FILE = "data/graph.json"
CHANGES_FILE = "data/changes.cypher"
SNAPSHOT_DIR = "data/snapshots"
NEO4J_DIR = "infra/neo4j"


def load_elements(args):
    if args.elements:
        with open(args.elements, encoding="utf-8") as f:
            return json.load(f)
    commit = get_json(f"{API}/projects/{args.project}/commits")[-1]["@id"]
    return get_json(f"{API}/projects/{args.project}/commits/{commit}/elements")


def edge_key(e):
    return (e["source"], e["type"], e["target"])


def diff(old, new):
    """Compare two graphs by id. Returns what was added, deleted and modified."""
    old_nodes = {n["id"]: n for n in old["nodes"]}
    new_nodes = {n["id"]: n for n in new["nodes"]}
    old_edges = {edge_key(e): e for e in old["edges"]}
    new_edges = {edge_key(e): e for e in new["edges"]}

    modified = []
    for nid in old_nodes.keys() & new_nodes.keys():
        before, after = old_nodes[nid]["props"], new_nodes[nid]["props"]
        if before != after:
            changes = {k: (before.get(k), after.get(k))
                       for k in before.keys() | after.keys() if before.get(k) != after.get(k)}
            modified.append((new_nodes[nid], changes))

    return {
        "nodes_added": [new_nodes[i] for i in new_nodes.keys() - old_nodes.keys()],
        "nodes_deleted": [old_nodes[i] for i in old_nodes.keys() - new_nodes.keys()],
        "nodes_modified": modified,
        "edges_added": [new_edges[k] for k in new_edges.keys() - old_edges.keys()],
        "edges_deleted": [old_edges[k] for k in old_edges.keys() - new_edges.keys()],
    }


def changes_to_cypher(d):
    """Only the changes, as Cypher. Unchanged nodes and edges are not touched."""
    q = ["// Generated by mapper/sync.py - incremental update"]
    for n in d["nodes_deleted"]:
        q.append(f"MATCH (n {{id: {json.dumps(n['id'])}}}) DETACH DELETE n;")
    for e in d["edges_deleted"]:
        q.append(f"MATCH (a {{id: {json.dumps(e['source'])}}})-[r:{e['type']}]->(b {{id: {json.dumps(e['target'])}}}) DELETE r;")
    for n in d["nodes_added"] + [m[0] for m in d["nodes_modified"]]:
        q.append(f"MERGE (n:{n['label']} {{id: {json.dumps(n['id'])}}}) "
                 f"SET n = {props({'id': n['id'], **n['props']})};")
    for e in d["edges_added"]:
        q.append(f"MATCH (a {{id: {json.dumps(e['source'])}}}), (b {{id: {json.dumps(e['target'])}}}) "
                 f"MERGE (a)-[r:{e['type']}]->(b) SET r += {props(e['props'])};")
    return "\n".join(q) + "\n"


def name_of(node_id, *graphs):
    for g in graphs:
        for n in g["nodes"]:
            if n["id"] == node_id:
                return n["props"].get("name", node_id[:8])
    return node_id[:8]


def report(d, old, new):
    total = sum(len(v) for v in d.values())
    print(f"Changes found: {total}")
    for n in d["nodes_added"]:
        print(f"  + node  {n['label']:<12} {n['props']['name']}")
    for n in d["nodes_deleted"]:
        print(f"  - node  {n['label']:<12} {n['props']['name']}")
    for n, changes in d["nodes_modified"]:
        for key, (before, after) in sorted(changes.items()):
            print(f"  ~ node  {n['label']:<12} {n['props']['name']}.{key}: {before} -> {after}")
    for e in d["edges_added"]:
        print(f"  + edge  {name_of(e['source'], new)} -{e['type']}-> {name_of(e['target'], new)}")
    for e in d["edges_deleted"]:
        print(f"  - edge  {name_of(e['source'], old)} -{e['type']}-> {name_of(e['target'], old)}")
    return total


def apply_to_neo4j():
    cmd = ["docker", "compose", "exec", "-T", "neo4j", "cypher-shell",
           "-u", "neo4j", "-p", "cubesat123", "-f", "/import/changes.cypher"]
    result = subprocess.run(cmd, cwd=NEO4J_DIR, capture_output=True, text=True)
    if result.returncode == 0:
        print("Neo4j updated (only the changes above).")
    else:
        print("Neo4j update failed:\n" + result.stderr)


def sync_once(args, rules):
    with open(GRAPH_FILE, encoding="utf-8") as f:
        old = json.load(f)
    elements = load_elements(args)
    new = Mapper(elements, rules).run()
    d = diff(old, new)
    total = report(d, old, new)
    if total == 0:
        return

    # keep our own version history (SysON has only one commit)
    stamp = datetime.datetime.now().strftime("%Y-%m-%d_%H-%M-%S")
    os.makedirs(SNAPSHOT_DIR, exist_ok=True)
    for path, data in ((f"{SNAPSHOT_DIR}/{stamp}_elements.json", elements),
                       (f"{SNAPSHOT_DIR}/{stamp}_graph.json", new),
                       ("data/elements.json", elements), (GRAPH_FILE, new)):
        with open(path, "w", encoding="utf-8") as f:
            json.dump(data, f, indent=2)
    with open(CHANGES_FILE, "w", encoding="utf-8") as f:
        f.write(changes_to_cypher(d))
    print(f"Saved: {CHANGES_FILE}, snapshot {stamp}")
    if args.apply:
        apply_to_neo4j()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--project", default=DEFAULT_PROJECT)
    parser.add_argument("--elements", help="read the model from this JSON file instead of the API")
    parser.add_argument("--apply", action="store_true", help="apply the changes to Neo4j")
    parser.add_argument("--watch", type=int, default=0, help="repeat every N seconds")
    args = parser.parse_args()
    with open(RULES_FILE, "rb") as f:
        rules = tomllib.load(f)

    while True:
        print(f"\n[{datetime.datetime.now():%H:%M:%S}] sync")
        sync_once(args, rules)
        if not args.watch:
            break
        time.sleep(args.watch)


if __name__ == "__main__":
    main()
